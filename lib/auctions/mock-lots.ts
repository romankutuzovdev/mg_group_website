function defaultEngine(lot: AuctionLot): string {
  if (lot.fuel === "Electric") return "EV";
  if (lot.fuel === "Hybrid") return "2.0L Hybrid";
  if (lot.fuel === "Diesel") return "2.0L Diesel";
  if (/x5|defender|f-150|pilot|highlander/i.test(lot.model)) return "3.0L";
  if (/320|a4|golf|corsa|c220/i.test(lot.model)) return "2.0L";
  if (/model 3|tesla/i.test(lot.model)) return "Dual Motor";
  return "2.0L";
}

function defaultCategory(lot: AuctionLot): string | undefined {
  if (/category b|cat b|parts only/i.test(lot.titleLabel)) return "B";
  return undefined;
}

function defaultBodyStyle(lot: AuctionLot): string {
  if (/defender|x5|pilot|highlander|qashqai|cr-v/i.test(lot.model)) return "SUV";
  if (/f-150|f150/i.test(lot.model)) return "Pickup";
  if (/sprinter|transit/i.test(lot.model)) return "Van";
  if (/corsa|golf|a4|320|model 3|c220/i.test(lot.model)) return "Sedan";
  return lot.model;
}

function enrichLot(lot: AuctionLot): AuctionLot {
  return {
    ...lot,
    engine: lot.engine ?? defaultEngine(lot),
    bodyStyle: lot.bodyStyle ?? defaultBodyStyle(lot),
    category: lot.category ?? defaultCategory(lot),
    inlandMiles: lot.region === "usa" ? (lot.inlandMiles ?? 450) : lot.inlandMiles,
    imageUrl: resolveLotImageUrl(lot.imageUrl, lot.make),
  };
}

export const MOCK_LOTS: AuctionLot[] = RAW_MOCK_LOTS.map(enrichLot);

export function getLotBySlug(slug: string): AuctionLot | undefined {
  return MOCK_LOTS.find((lot) => lot.slug === slug);
}

export function getModelsForMake(make: string): string[] {
  const models = new Set<string>();
  for (const lot of MOCK_LOTS) {
    if (lot.make === make) models.add(lot.model);
  }
  return Array.from(models).sort();
}
